// Vendor-offering catalogue import (BID-OFFERING-CLASSIFICATION).
//
//   npx tsx scripts/offering-catalogue/import.ts            regenerate the outputs
//   npx tsx scripts/offering-catalogue/import.ts --check    fail if any output is out of date
//
// Input:  shared/offering-catalogue/source/<version>.sheets.json  (versioned local
//         snapshot of the Google Sheet, with provenance and content checksum —
//         registration never depends on Google Sheets being reachable)
//         shared/offering-catalogue/item-ids.json                 (persisted item IDs)
//         shared/offering-catalogue/labels.ar.json                (Arabic labels by ID)
//         shared/offering-catalogue/catalogue.json                (previous output, if any)
// Output: shared/offering-catalogue/catalogue.json                (what the app reads)
//         shared/offering-catalogue/item-ids.json                 (new items appended)
//         migrations/0021_offering_catalogue_seed.sql             (idempotent DB upsert)
//
// No database is touched. Any validation error aborts before anything is written.

import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { createHash } from "node:crypto";
import path from "node:path";
import { buildCatalogue, type SourceSnapshot } from "../../shared/offering-catalogue/build";
import type { ItemIdMap, OfferingCatalogue } from "../../shared/offering-catalogue/types";

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), "../..");
const DIR = path.join(ROOT, "shared/offering-catalogue");
const SOURCE = path.join(DIR, "source/registration-1.0-draft.sheets.json");
const OUT_CATALOGUE = path.join(DIR, "catalogue.json");
const OUT_IDS = path.join(DIR, "item-ids.json");
const AR = path.join(DIR, "labels.ar.json");
const OUT_SQL = path.join(ROOT, "migrations/0021_offering_catalogue_seed.sql");

const readJson = <T>(p: string, fallback: T): T => (existsSync(p) ? JSON.parse(readFileSync(p, "utf8")) : fallback);

/** One record per line: stable, reviewable diffs. */
export function formatCatalogue(c: OfferingCatalogue): string {
  const list = (rows: unknown[]) => "[\n" + rows.map((r) => JSON.stringify(r)).join(",\n") + "\n]";
  return `{"version":${JSON.stringify(c.version)},\n"provenance":${JSON.stringify(c.provenance)},\n` +
    `"sectors":${list(c.sectors)},\n"specializations":${list(c.specializations)},\n` +
    `"groups":${list(c.groups)},\n"items":${list(c.items)}}\n`;
}

const q = (s: string | null) => (s === null ? "NULL" : `'${s.replace(/'/g, "''")}'`);

export function seedSql(c: OfferingCatalogue): string {
  const v = q(c.version);
  const rows = (vals: string[][]) => vals.map((r) => `  (${r.join(", ")})`).join(",\n");
  return `-- 0021: vendor-offering catalogue seed — GENERATED by scripts/offering-catalogue/import.ts.
-- Do not edit by hand. Catalogue ${c.version}, source checksum ${c.provenance.checksum}.
--
-- Idempotent: upserts every catalogue record (labels, type, status) by its
-- stable ID. Re-running it, or running a later version's seed, never deletes a
-- record and never moves one to another parent — the final check aborts the
-- whole transaction if a stored record's parent differs from this file.
-- Requires 0020_vendor_offerings.sql. Not run by the build; needs approval.

BEGIN;

INSERT INTO offering_catalogue_versions (version, source_url, source_revision_id, source_modified_at, retrieved_at, checksum)
VALUES (${v}, ${q(c.provenance.sourceUrl)}, ${q(c.provenance.sourceRevisionId)}, ${q(c.provenance.sourceModifiedTime)}, ${q(c.provenance.retrievedAt)}, ${q(c.provenance.checksum)})
ON CONFLICT (version) DO UPDATE SET checksum = EXCLUDED.checksum WHERE offering_catalogue_versions.checksum = EXCLUDED.checksum;
-- A version string is never reused for different content:
DO $$ BEGIN
  IF (SELECT checksum FROM offering_catalogue_versions WHERE version = ${v}) <> ${q(c.provenance.checksum)} THEN
    RAISE EXCEPTION 'Catalogue version % already exists with a different checksum', ${v};
  END IF;
END $$;

CREATE TEMP TABLE seed_sectors (id text, label_source text, label_en text, label_ar text, status text) ON COMMIT DROP;
INSERT INTO seed_sectors VALUES
${rows(c.sectors.map((s) => [q(s.id), q(s.src), q(s.en), q(s.ar), q(s.status)]))};

CREATE TEMP TABLE seed_specializations (id text, sector_id text, label_source text, label_en text, label_ar text, status text) ON COMMIT DROP;
INSERT INTO seed_specializations VALUES
${rows(c.specializations.map((s) => [q(s.id), q(s.sectorId), q(s.src), q(s.en), q(s.ar), q(s.status)]))};

CREATE TEMP TABLE seed_groups (id text, specialization_id text, offering_type text, examples_source text, label_source text, label_en text, label_ar text, status text) ON COMMIT DROP;
INSERT INTO seed_groups VALUES
${rows(c.groups.map((g) => [q(g.id), q(g.specializationId), q(g.type), q(g.examples), q(g.src), q(g.en), q(g.ar), q(g.status)]))};

CREATE TEMP TABLE seed_items (id text, group_id text, provenance text, label_source text, label_en text, label_ar text, status text) ON COMMIT DROP;
INSERT INTO seed_items VALUES
${rows(c.items.map((i) => [q(i.id), q(i.groupId), q(i.provenance), q(i.src), q(i.en), q(i.ar), q(i.status)]))};

-- Parents never change for an existing ID (abort instead of reclassifying).
DO $$ BEGIN
  IF EXISTS (SELECT 1 FROM seed_specializations s JOIN offering_specializations o USING (id) WHERE o.sector_id <> s.sector_id)
  OR EXISTS (SELECT 1 FROM seed_groups s JOIN offering_groups o USING (id) WHERE o.specialization_id <> s.specialization_id)
  OR EXISTS (SELECT 1 FROM seed_items s JOIN offering_items o USING (id) WHERE o.group_id <> s.group_id) THEN
    RAISE EXCEPTION 'A catalogue record would move to a different parent; resolve with a new ID';
  END IF;
END $$;

INSERT INTO offering_sectors (id, label_source, label_en, label_ar, status, introduced_in)
SELECT id, label_source, label_en, label_ar, status, ${v} FROM seed_sectors
ON CONFLICT (id) DO UPDATE SET label_source = EXCLUDED.label_source, label_en = EXCLUDED.label_en, label_ar = EXCLUDED.label_ar, status = EXCLUDED.status, updated_at = now()
WHERE (offering_sectors.label_source, offering_sectors.label_en, offering_sectors.label_ar, offering_sectors.status)
  IS DISTINCT FROM (EXCLUDED.label_source, EXCLUDED.label_en, EXCLUDED.label_ar, EXCLUDED.status);

INSERT INTO offering_specializations (id, sector_id, label_source, label_en, label_ar, status, introduced_in)
SELECT id, sector_id, label_source, label_en, label_ar, status, ${v} FROM seed_specializations
ON CONFLICT (id) DO UPDATE SET label_source = EXCLUDED.label_source, label_en = EXCLUDED.label_en, label_ar = EXCLUDED.label_ar, status = EXCLUDED.status, updated_at = now()
WHERE (offering_specializations.label_source, offering_specializations.label_en, offering_specializations.label_ar, offering_specializations.status)
  IS DISTINCT FROM (EXCLUDED.label_source, EXCLUDED.label_en, EXCLUDED.label_ar, EXCLUDED.status);

INSERT INTO offering_groups (id, specialization_id, offering_type, examples_source, label_source, label_en, label_ar, status, introduced_in)
SELECT id, specialization_id, offering_type, examples_source, label_source, label_en, label_ar, status, ${v} FROM seed_groups
ON CONFLICT (id) DO UPDATE SET offering_type = EXCLUDED.offering_type, examples_source = EXCLUDED.examples_source, label_source = EXCLUDED.label_source, label_en = EXCLUDED.label_en, label_ar = EXCLUDED.label_ar, status = EXCLUDED.status, updated_at = now()
WHERE (offering_groups.offering_type, offering_groups.examples_source, offering_groups.label_source, offering_groups.label_en, offering_groups.label_ar, offering_groups.status)
  IS DISTINCT FROM (EXCLUDED.offering_type, EXCLUDED.examples_source, EXCLUDED.label_source, EXCLUDED.label_en, EXCLUDED.label_ar, EXCLUDED.status);

INSERT INTO offering_items (id, group_id, provenance, label_source, label_en, label_ar, status, introduced_in)
SELECT id, group_id, provenance, label_source, label_en, label_ar, status, ${v} FROM seed_items
ON CONFLICT (id) DO UPDATE SET label_source = EXCLUDED.label_source, label_en = EXCLUDED.label_en, label_ar = EXCLUDED.label_ar, status = EXCLUDED.status, updated_at = now()
WHERE (offering_items.label_source, offering_items.label_en, offering_items.label_ar, offering_items.status)
  IS DISTINCT FROM (EXCLUDED.label_source, EXCLUDED.label_en, EXCLUDED.label_ar, EXCLUDED.status);

-- Records stored earlier but absent from this file stay; they are NOT deleted.
DO $$ BEGIN
  IF (SELECT count(*) FROM offering_sectors WHERE status = 'active') <> ${c.sectors.filter((s) => s.status === "active").length}
  OR (SELECT count(*) FROM offering_specializations WHERE status = 'active') <> ${c.specializations.filter((s) => s.status === "active").length}
  OR (SELECT count(*) FROM offering_groups WHERE status = 'active') <> ${c.groups.filter((s) => s.status === "active").length}
  OR (SELECT count(*) FROM offering_items WHERE status = 'active') <> ${c.items.filter((s) => s.status === "active").length} THEN
    RAISE EXCEPTION 'Active catalogue counts differ from catalogue ${c.version}: a stored record is missing from this seed';
  END IF;
END $$;

COMMIT;
`;
}

function main() {
  const check = process.argv.includes("--check");
  const snapshot = readJson<SourceSnapshot>(SOURCE, null as any);
  const checksum = createHash("sha256").update(JSON.stringify(snapshot.tabs)).digest("hex");
  const itemIds = readJson<ItemIdMap>(OUT_IDS, {
    note: "Persisted item IDs. Assigned once by the importer; never renumber or reuse. Key = group ID + normalised source example.",
    items: {},
  });
  const previous = readJson<OfferingCatalogue | null>(OUT_CATALOGUE, null);
  const arabic = readJson<{ labels: Record<string, string> }>(AR, { labels: {} }).labels;

  const result = buildCatalogue({ snapshot, itemIds, arabic, previous, checksum });
  const errors = result.issues.filter((i) => i.level === "error");
  for (const i of result.issues) console.log(`${i.level.toUpperCase()} ${i.code} ${i.ref}: ${i.message}`);
  console.log(JSON.stringify({ version: result.catalogue.version, checksum, ...result.stats }));
  if (errors.length > 0) {
    console.error(`${errors.length} error(s); nothing written.`);
    process.exit(1);
  }

  const outputs: [string, string][] = [
    [OUT_CATALOGUE, formatCatalogue(result.catalogue)],
    [OUT_IDS, JSON.stringify(result.itemIds, null, 1) + "\n"],
    [OUT_SQL, seedSql(result.catalogue)],
  ];
  const stale = outputs.filter(([p, body]) => !existsSync(p) || readFileSync(p, "utf8") !== body);
  if (check) {
    for (const [p] of stale) console.error(`out of date: ${path.relative(ROOT, p)}`);
    process.exit(stale.length ? 1 : 0);
  }
  for (const [p, body] of stale) writeFileSync(p, body);
  console.log(stale.length ? `wrote ${stale.map(([p]) => path.relative(ROOT, p)).join(", ")}` : "up to date (no changes)");
}

if (process.argv[1] && import.meta.url === new URL(`file://${path.resolve(process.argv[1])}`).href) main();
